def validate_citations(cites_used, bib):
    if not bib:
        return
    undefined = [k for k in cites_used if k not in bib]
    if undefined:
        raise SystemExit(f'UNDEFINED CITATION KEYS: {undefined}')
    orphans = [k for k in bib if k not in cites_used]
    if orphans:
        print(f'WARNING: orphan bib entries: {orphans}')

