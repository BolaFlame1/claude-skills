def set_line_spacing(paragraph, spacing=2.0):
    pPr = paragraph._p.get_or_add_pPr()
    lSpc = OxmlElement('w:spacing')
    lSpc.set(qn('w:line'), str(int(spacing * 240)))
    lSpc.set(qn('w:lineRule'), 'auto')
    pPr.append(lSpc)

def add_run_with_font(paragraph, text, bold=False, italic=False,
                      superscript=False, size_pt=12):
    run = paragraph.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size_pt)
    if superscript:
        run.font.superscript = True
    return run

def resolve_cites(text):
    pattern = re.compile(r'\[@([^\]]+)\]')
    parts, last = [], 0
    for m in pattern.finditer(text):
        if m.start() > last:
            parts.append((text[last:m.start()], False))
        keys = [k.strip().lstrip('@') for k in m.group(1).split(';')]
        nums = [str(_resolve_key(k) if k in _bib else f'?{k}?') for k in keys]
        parts.append((','.join(nums), True))
        last = m.end()
    if last < len(text):
        parts.append((text[last:], False))
    return parts

def _add_inline_formatted(paragraph, text, base_bold=False,
                           base_italic=False, size_pt=12):
    pattern = re.compile(r'\*\*(.+?)\*\*|\*(.+?)\*')
    last = 0
    for m in pattern.finditer(text):
        if m.start() > last:
            add_run_with_font(paragraph, text[last:m.start()],
                              bold=base_bold, italic=base_italic, size_pt=size_pt)
        if m.group(1) is not None:
            add_run_with_font(paragraph, m.group(1), bold=True,
                              italic=base_italic, size_pt=size_pt)
        else:
            add_run_with_font(paragraph, m.group(2), bold=base_bold,
                              italic=True, size_pt=size_pt)
        last = m.end()
    if last < len(text):
        add_run_with_font(paragraph, text[last:], bold=base_bold,
                          italic=base_italic, size_pt=size_pt)

def add_para(doc, text, bold=False, italic=False,
             alignment=WD_ALIGN_PARAGRAPH.LEFT, space_before=0, size_pt=12):
    _CITE_SOURCE.append(text)
    p = doc.add_paragraph()
    p.alignment = alignment
    if space_before:
        p.paragraph_format.space_before = Pt(space_before)
    set_line_spacing(p)
    for chunk, is_sup in resolve_cites(text.strip()):
        if is_sup:
            add_run_with_font(p, chunk, superscript=True, size_pt=size_pt)
        else:
            _add_inline_formatted(p, chunk, base_bold=bold,
                                  base_italic=italic, size_pt=size_pt)
    return p

def add_heading(doc, text, level=1, size_pt=None, bold=True):
    sizes = {1: 14, 2: 12, 3: 12}
    sz = size_pt or sizes.get(level, 12)
    p = doc.add_paragraph()
    set_line_spacing(p)
    run = p.add_run(text)
    run.bold = bold
    run.italic = (level == 3)
    run.font.size = Pt(sz)
    if level == 1:
        p.paragraph_format.space_before = Pt(12)
    elif level == 2:
        p.paragraph_format.space_before = Pt(6)
    return p

